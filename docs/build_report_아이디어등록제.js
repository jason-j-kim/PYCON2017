// 굵게 표시가 필요한 곳은 조각 배열로 넘긴다. 색은 쓰지 않는다.
function para(parts, o = {}) {
  if (typeof parts === "string") parts = [parts];
  return new Paragraph({
    spacing: { after: o.after ?? 130, line: o.line ?? LINE },
    alignment: o.align,
    indent: o.indent,
    children: parts.map(p => {
      if (typeof p === "string")
        return new TextRun({ text: p, font: F, size: o.size ?? BODY, bold: o.bold });
      if (p.fn !== undefined) return new FootnoteReferenceRun(p.fn);
      return new TextRun({ text: p.t, font: F, size: o.size ?? BODY, bold: p.b, italics: p.i });
    }),
  });
}

