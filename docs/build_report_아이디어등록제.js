// ── 문단 도구 ──────────────────────────────────────────────────────────
const P = (text, o = {}) => new Paragraph({
  spacing: { after: o.after ?? 140, line: o.line ?? 300 },
  alignment: o.align,
  indent: o.indent,
  children: [new TextRun({
    text, font: F, size: o.size ?? 20, bold: o.bold, italics: o.italics,
    color: o.color ?? INK,
  })],
});

// 굵은 조각을 섞은 문단
const PR = (parts, o = {}) => new Paragraph({
  spacing: { after: o.after ?? 140, line: o.line ?? 300 },
  alignment: o.align,
  children: parts.map(p => typeof p === "string"
    ? new TextRun({ text: p, font: F, size: o.size ?? 20, color: o.color ?? INK })
    : new TextRun({ text: p.t, font: F, size: o.size ?? 20, bold: p.b, italics: p.i,
                    color: p.c ?? o.color ?? INK })),
});

