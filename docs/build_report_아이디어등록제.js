// 음영 없이 선만 쓴다. 머리행은 굵게로만 구분한다.
function table(widths, head, rows, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (t, w, opt = {}) => new TableCell({
    width: { size: w, type: WidthType.DXA },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    verticalAlign: "center",
    children: String(t).split("\n").map((line, i, arr) => new Paragraph({
      spacing: { after: i === arr.length - 1 ? 0 : 30, line: 280 },
      alignment: opt.align,
      children: [new TextRun({
        text: line, font: F, size: o.size ?? SMALL, bold: opt.bold,
      })],
    })),
  });
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    borders: {
      top: RULE, bottom: RULE, left: THIN, right: THIN,
      insideHorizontal: THIN, insideVertical: THIN,
    },
    rows: [
      new TableRow({
        tableHeader: true, cantSplit: true,
        children: head.map((t, i) => cell(t, widths[i], { bold: true, align: o.headAlign })),
      }),
      ...rows.map(r => new TableRow({
        cantSplit: true,
        children: r.map((t, i) => cell(t, widths[i], {
          bold: o.boldCol === i,
          align: o.numAlign && i > 0 ? AlignmentType.RIGHT : undefined,
        })),
      })),
    ],
  });
}

