const SPACE = (n = 120) => new Paragraph({ spacing: { after: n }, children: [] });

// ── 표 ────────────────────────────────────────────────────────────────
function TBL(widths, head, rows, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (t, w, opt = {}) => new TableCell({
    width: { size: w, type: WidthType.DXA },
    shading: opt.head ? { type: ShadingType.CLEAR, fill: "E8EEF4" }
                      : (opt.zebra ? { type: ShadingType.CLEAR, fill: "FAF9F6" } : undefined),
    margins: { top: 90, bottom: 90, left: 130, right: 130 },
    verticalAlign: "center",
    children: String(t).split("\n").map((line, i, arr) => new Paragraph({
      spacing: { after: i === arr.length - 1 ? 0 : 40, line: 260 },
      alignment: opt.align,
      children: [new TextRun({
        text: line, font: F, size: opt.size ?? 18,
        bold: opt.head || opt.bold, color: opt.head ? ACC : INK,
      })],
    })),
  });
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: ACC },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: ACC },
      left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: LINE },
      insideVertical: { style: BorderStyle.SINGLE, size: 1, color: "EDEBE5" },
    },
    rows: [
      new TableRow({
        tableHeader: true,
        cantSplit: true,
        children: head.map((t, i) => cell(t, widths[i], { head: true, size: o.size, align: o.align })),
      }),
      ...rows.map((r, ri) => new TableRow({
        cantSplit: true,
        children: r.map((t, i) => cell(t, widths[i], {
          zebra: ri % 2 === 1, size: o.size, bold: o.boldCol === i,
          align: o.numAlign && i > 0 ? AlignmentType.RIGHT : o.align,
        })),
      })),
    ],
  });
}

