# -*- coding: utf-8 -*-
"""연구 참여 계획서 — 「온 국민 아이디어 등록제」 설명자료의 후속 작업 기준.

설명자료가 5.4절과 6.4·6.5절에서 스스로 남긴 숙제 목록이 있다. 그것이
곧 후속 연구의 의제다. 계획서를 새로 지어낼 이유가 없으므로 그 목록을
축으로 삼는다.

설명자료에서 가장 정직한 문장은 맺음말에 있다.

    "지금 입증된 것은 극단 사례를 가르는 능력이고, 실제 국민 제안이
     몰릴 중간대에서의 판별력은 아직 재지 않았다."

이 한 문장이 연구 의제 전체다. 그리고 이 문서의 중심 논지는 여기에
성장이론을 붙이는 데서 나온다 — 극단은 선별 장치가 없어도 갈린다.
선별의 값어치는 전부 중간대에 있다. 그런데 그 중간대가 미검증이다.

문체 규칙은 앞 판과 같다. 문단 끝을 한 가지 말로 반복하지 않는다.
문단 길이를 고르게 만들지 않는다. "첫째·둘째"로 늘어놓지 않는다.
"""
import os
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor, Cm

KO = "맑은 고딕"
TITLE, HEAD, BODY, SMALL = Pt(15), Pt(12), Pt(11), Pt(10)
BLACK = RGBColor(0, 0, 0)

doc = Document()
sec = doc.sections[0]
sec.top_margin, sec.bottom_margin = Cm(2.4), Cm(2.2)
sec.left_margin, sec.right_margin = Cm(2.7), Cm(2.7)

st = doc.styles["Normal"]
st.font.name = KO
st.font.size = BODY
st.font.color.rgb = BLACK
st.element.rPr.rFonts.set(qn("w:eastAsia"), KO)
st.paragraph_format.line_spacing = Pt(19)
st.paragraph_format.space_after = Pt(9)


def style_run(r, size=BODY, bold=False):
    r.font.name = KO
    r.font.size = size
    r.font.bold = bold
    r.font.color.rgb = BLACK
    rpr = r._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = rpr.makeelement(qn("w:rFonts"), {}); rpr.insert(0, rf)
    for a in ("w:eastAsia", "w:ascii", "w:hAnsi"):
        rf.set(qn(a), KO)
    return r


def p(text="", size=BODY, bold=False, after=9, before=0, indent=0,
      align=None, line=19, keep=False, first=0.0):
    par = doc.add_paragraph()
    f = par.paragraph_format
    f.space_after, f.space_before, f.line_spacing = Pt(after), Pt(before), Pt(line)
    if indent:
        f.left_indent = Cm(indent)
    if first:
        f.first_line_indent = Cm(first)
    if align is not None:
        par.alignment = align
    f.keep_together = True
    if keep:
        f.keep_with_next = True
    if text:
        style_run(par.add_run(text), size, bold)
    return par


def para(*chunks):
    par = p("", first=0.5)
    for c in chunks:
        if isinstance(c, tuple):
            style_run(par.add_run(c[0]), BODY, c[1])
        else:
            style_run(par.add_run(c), BODY, False)
    return par


def quote(text):
    par = p(text, SMALL, indent=1.0, after=11, line=16)
    return par


def h(text):
    return p(text, HEAD, True, after=10, before=22, keep=True)


def table(rows, widths):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for gc, w in zip(t._tbl.find(qn("w:tblGrid")), widths):
        gc.set(qn("w:w"), str(w))
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.cell(ri, ci)
            cell.width = Pt(widths[ci] / 20)
            for li, line in enumerate(str(val).split("\n")):
                par = cell.paragraphs[0] if li == 0 else cell.add_paragraph()
                par.paragraph_format.space_after = Pt(1)
                par.paragraph_format.space_before = Pt(1)
                par.paragraph_format.line_spacing = Pt(14)
                par.paragraph_format.keep_with_next = (ri < len(rows) - 1)
                if ri == 0:
                    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
                style_run(par.add_run(line), SMALL, ri == 0)
        t.rows[ri]._tr.get_or_add_trPr().append(
            t.rows[ri]._tr.makeelement(qn("w:cantSplit"), {}))
    tblPr = t._tbl.tblPr
    b = tblPr.makeelement(qn("w:tblBorders"), {})
    for edge, s in (("top", "6"), ("bottom", "6"), ("left", "4"), ("right", "4"),
                    ("insideH", "2"), ("insideV", "2")):
        e = b.makeelement(qn("w:" + edge), {})
        e.set(qn("w:val"), "single"); e.set(qn("w:sz"), s)
        e.set(qn("w:color"), "000000"); e.set(qn("w:space"), "0")
        b.append(e)
    tblPr.append(b)
    t.rows[0]._tr.get_or_add_trPr().append(
        t.rows[0]._tr.makeelement(qn("w:tblHeader"), {}))
    p("", after=10)
    return t


C = WD_ALIGN_PARAGRAPH.CENTER
R = WD_ALIGN_PARAGRAPH.RIGHT

