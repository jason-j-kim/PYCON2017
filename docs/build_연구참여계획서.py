"""연구 참여 계획서 — 문장체.

앞서 쓴 개조식 판을 버린다. 개조식은 한 일을 늘어놓기에 좋은 형식이고,
그래서 자꾸 실적 목록이 된다. 이 문서가 보여야 할 것은 실적이 아니라
무엇을 어떻게 보느냐이므로 문장으로 쓴다.

세 가지를 지킨다.
  (1) 이미 해냈다는 투로 쓰지 않는다. 시제를 앞으로 둔다.
  (2) 기존 시스템이 낸 수치를 근거로 끌어오지 않는다.
  (3) 관점과 역량을 쓴다 — 무엇을 믿고 무엇을 할 수 있는가.

문단은 주제문으로 시작하고 근거로 이어 간다. 소제목은 남기되 본문은
개조식 기호를 쓰지 않는다.
"""
import os
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor, Cm

KO = "맑은 고딕"
TITLE, HEAD, BODY, SMALL = Pt(15), Pt(12), Pt(11), Pt(10)
BLACK = RGBColor(0, 0, 0)

doc = Document()
sec = doc.sections[0]
sec.top_margin, sec.bottom_margin = Cm(2.4), Cm(2.2)
sec.left_margin, sec.right_margin = Cm(2.7), Cm(2.7)

st = doc.styles["Normal"]
st.font.name = KO
st.font.size = BODY
st.font.color.rgb = BLACK
st.element.rPr.rFonts.set(qn("w:eastAsia"), KO)
st.paragraph_format.line_spacing = Pt(19)
st.paragraph_format.space_after = Pt(9)


def style_run(r, size=BODY, bold=False):
    r.font.name = KO
    r.font.size = size
    r.font.bold = bold
    r.font.color.rgb = BLACK
    rpr = r._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = rpr.makeelement(qn("w:rFonts"), {}); rpr.insert(0, rf)
    for a in ("w:eastAsia", "w:ascii", "w:hAnsi"):
        rf.set(qn(a), KO)
    return r


def p(text="", size=BODY, bold=False, after=9, before=0, indent=0,
      align=None, line=19, keep=False, first=0.0):
    par = doc.add_paragraph()
    f = par.paragraph_format
    f.space_after, f.space_before, f.line_spacing = Pt(after), Pt(before), Pt(line)
    if indent:
        f.left_indent = Cm(indent)
    if first:
        f.first_line_indent = Cm(first)
    if align is not None:
        par.alignment = align
    f.keep_together = True
    if keep:
        f.keep_with_next = True
    if text:
        style_run(par.add_run(text), size, bold)
    return par


def para(*chunks):
    """본문 한 문단. (글, 굵기) 짝을 이어 붙인다."""
    par = p("", first=0.5)
    for c in chunks:
        if isinstance(c, tuple):
            style_run(par.add_run(c[0]), BODY, c[1])
        else:
            style_run(par.add_run(c), BODY, False)
    return par


def h(text):
    return p(text, HEAD, True, after=9, before=20, keep=True)


C = WD_ALIGN_PARAGRAPH.CENTER
R = WD_ALIGN_PARAGRAPH.RIGHT

